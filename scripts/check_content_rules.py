_LINTOK = re.compile(r"<!--\s*lint-ok:\s*([\w,\-]+)")

# 禁止パターン ID の書式: YYYYMMDD-slug（登録日 + 内容スラッグ）。
# 連番（N1, N2, …）は並列 PR で同じ番号を取り合って衝突するため禁止する。
