# 各エントリ (id, matcher, desc, sample)。matcher は正規表現(compiled) か
# 述語関数(line->bool) のどちらか。sample は self-test が必ず検出できねばならぬ
# 最小文字列（サンプル未定義のパターンを作れない構造にする）。
