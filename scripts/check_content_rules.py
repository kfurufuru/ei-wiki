def _both(pat_a: str, pat_b: str):
    """同一行に pat_a と pat_b の両方（順不同）を含めば True の述語を作る。"""
    ra, rb = re.compile(pat_a), re.compile(pat_b)
    return lambda line: bool(ra.search(line)) and bool(rb.search(line))


def _both_unless(pat_a: str, pat_b: str, neg: str):
    """_both と同じだが、同一行に neg があれば除外する述語を作る。
    誤りを是正した解説文（「〜は確認できない」等の否定形）を巻き込まないための負対照付き版。"""
    ra, rb, rn = re.compile(pat_a), re.compile(pat_b), re.compile(neg)
    return lambda line: (bool(ra.search(line)) and bool(rb.search(line))
                         and not rn.search(line))


