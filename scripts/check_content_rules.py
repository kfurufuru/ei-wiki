def load_docs():
    """docs/ 配下の .md（templates/・includes/ 除外）を (相対パス, 行リスト) で返す。"""
    out = []
    for p in sorted(DOCS.rglob("*.md")):
        rel_parts = p.relative_to(DOCS).parts
        if rel_parts and rel_parts[0] in EXCLUDE_DIRS:
            continue
        rel = str(p.relative_to(ROOT)).replace("\\", "/")
        out.append((rel, p.read_text(encoding="utf-8").splitlines()))
    return out


def scan_lines(lines):
    """禁止パターンを行単位走査。lint-ok（同一行/直前行・ID照合）で免除。
    (行番号1始まり, ID, desc, 行内容) のリストを返す。"""
    out = []
    for i, line in enumerate(lines):
        exempt = lintok_ids(line)
        if i > 0:
            exempt |= lintok_ids(lines[i - 1])
        for pid, matcher, desc, _sample in FORBIDDEN:
            if pid in exempt:
                continue
            if _matches(matcher, line):
                out.append((i + 1, pid, desc, line))
    return out


def check_forbidden(docs):
    """検査1: 数値矛盾 lint。違反 (rel, 行番号, ID, desc, 行内容) のリスト。"""
    violations = []
    for rel, lines in docs:
        for lineno, pid, desc, content in scan_lines(lines):
            violations.append((rel, lineno, pid, desc, content))
    return violations


def parse_frontmatter(lines):
    """先頭 --- 〜 --- のフロントマター本文行を返す。無し/未終端なら None。"""
    if not lines or lines[0].strip() != "---":
        return None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i]
    return None


def _key_state(fm_lines, key):
    """frontmatter 内の key の状態を返す。
    (存在するか, インライン値 or None, 充足するか)。
    充足条件: キー行があり、同一行に非空値がある or 次行以降に `- ` 項目が1つ以上。"""
    kre = re.compile(rf"^{re.escape(key)}\s*:(.*)$")
    for idx, line in enumerate(fm_lines):
        m = kre.match(line)
        if not m:
            continue
        inline = m.group(1).strip()
        if inline and inline not in ("[]", "{}"):
            return True, inline, True
        # ブロックリスト形式の子項目を探す（次のトップレベルキーまで）
        for j in range(idx + 1, len(fm_lines)):
            nxt = fm_lines[j]
            if re.match(r"^\S.*:", nxt):  # 次のトップレベルキー
                break
            if re.match(r"^\s*-\s+\S", nxt):
                return True, None, True
        return True, inline, False  # キーはあるが値が空
    return False, None, False


def check_frontmatter(docs):
    """検査2: frontmatter 必須キー lint。違反メッセージ文字列のリスト。"""
    fails = []
    for rel, lines in docs:
        fm = parse_frontmatter(lines)
        if fm is None:
            for key in REQUIRED_FM_KEYS:
                fails.append(f"{rel}: frontmatter '{key}' 欠落")
            continue
        for key in REQUIRED_FM_KEYS:
            present, inline, ok = _key_state(fm, key)
            if not ok:
                fails.append(f"{rel}: frontmatter '{key}' 欠落/不正")
                continue
            if key == "last_verified":
                val = (inline or "").strip().strip('"').strip("'")
                if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", val):
                    fails.append(f"{rel}: frontmatter 'last_verified' 欠落/不正")
                    continue
                try:
                    datetime.strptime(val, "%Y-%m-%d")
                except ValueError:
                    fails.append(f"{rel}: frontmatter 'last_verified' 欠落/不正")
    return fails


def check_boost(docs):
    """検査3: 06-trouble/*.md は search.boost>=2 を要求。違反メッセージのリスト。"""
    fails = []
    for rel, lines in docs:
        if not rel.startswith("docs/06-trouble/"):
            continue
        fm = parse_frontmatter(lines)
        if fm is None:
            fails.append(f"{rel}: 06-trouble frontmatter 無し（search/boost 検証不能）")
            continue
        s_idx = None
        for idx, line in enumerate(fm):
            if re.match(r"^search\s*:", line):
                s_idx = idx
                break
        if s_idx is None:
            fails.append(f"{rel}: 06-trouble 'search:' ブロック欠落")
            continue
        found = None
        for j in range(s_idx + 1, len(fm)):
            line = fm[j]
            if re.match(r"^\S", line):  # search ブロックを抜けた
                break
            m = re.match(r"^\s+boost\s*:\s*(\d+)", line)
            if m:
                found = int(m.group(1))
                break
        if found is None:
            fails.append(f"{rel}: 06-trouble 'boost:' 欠落")
        elif found < 2:
            fails.append(f"{rel}: 06-trouble boost={found} が2未満")
    return fails


# コードブロック言語未指定の総数ラチェット基準。
# 既存の裸フェンス（ASCII図・数式ブロックの慣行）は R30（一括自動変換の教訓）を
# 避けて据え置くが、この基準を超える＝新規ページ/加筆で裸フェンスを増やしたら FAIL。
# 既存分は免罪しつつ増加だけを止める。既存を`text`化して減らしたらこの値も下げてよい。
# 2026-07-28: 図解パイロット（ASCII図→SVG/mermaid）で 242→237、
# 続く 06-trouble 3ページの mermaid 化で 237→235、
# 絶縁トレンド図の SVG 化で 235→234 に減ったので基準も下げる。
# 2026-07-30: 工事計画届出フローの裸フェンスを ```text 化して 234→233。
# 2026-08-01: panel-hmi の表示灯配置例を ```text 化（＋他PRの削減分）で実測 230 に低下したため追随。
# 2026-08-01: panel-design の充填率ブロックを ```text 化して 230→229。
CODEBLOCK_WARN_BASELINE = 225


def warn_codeblocks(docs):
    """検査4: コードブロック言語未指定を数える（WARN・exit 非影響）。
    開始/終了フェンスをトグルで追跡し、終了フェンスを開始と誤認しない。
    (総件数, ファイル別件数dict) を返す。"""
    total = 0
    per_file = {}
    fence = re.compile(r"^\s*```(\S*)")
    for rel, lines in docs:
        in_block = False
        for line in lines:
            m = fence.match(line)
            if not m:
                continue
            if not in_block:
                in_block = True
                if not m.group(1):  # 言語トークン無し
                    total += 1
                    per_file[rel] = per_file.get(rel, 0) + 1
            else:
                in_block = False  # 終了フェンス（トークンは無視）
    return total, per_file


# ---------------------------------------------------------------------------
# 検査5: インライン SVG の記法規約
# ---------------------------------------------------------------------------
# 規約の根拠（いずれも 2026-07-28 に公開サイト/隔離ビルドで実測）:
#  - width/height を省くと Material の .md-typeset figure{width:fit-content} と
#    固有寸法なし SVG の組合せで figure 幅が解決できず約26pxに潰れる。
#  - --md-primary-fg-color は color-switcher.js の8色 x 2スキーム16通り中4通りで、
#    --md-accent-fg-color はライトで、背景とのコントラストが 3:1 を下回る。
#    情報を担う線・文字は --md-default-fg-color(--light) のみ使う。
#  - 色のハードコードはダークモードで見えなくなる（seigyoban-tekkyo の実害あり）。
#    意味色が要る場合は custom.css の --ei-fig-* トークンを使う。
#  - <figure markdown="..."> は SVG 内テキストを Markdown 処理して壊す。属性を付けない。
#  - <svg> は必ず <figure> で包む（2026-07-30 実測）。python-markdown は <svg> を
#    ブロック要素として認識しないため、生の <svg> はインラインHTML扱いで <p> に
#    包まれ、内部の HTML コメントや空行のたびに <p> が分割されて SVG がバラバラに
#    なる（ビルド後HTMLに <p><line .../> が並び、図の中身が丸ごと失われる）。
#    <figure> はブロック要素として認識されるので中身が raw のまま通る。
#    lint も mkdocs build --strict も緑のまま素通りする種類の事故なので機械化した。
SVG_BANNED_VARS = ("--md-primary-fg-color", "--md-accent-fg-color",
                   "--md-default-fg-color--lighter")
_SVG_OPEN = re.compile(r"<svg\b[^>]*>", re.I)
_SVG_BLOCK = re.compile(r"<svg\b.*?</svg>", re.I | re.S)
_HEXCOLOR = re.compile(r'(?:fill|stroke|stop-color|color)\s*[:=]\s*"?\s*(#[0-9a-fA-F]{3,8})')
_FIGURE_MD = re.compile(r"<figure\b[^>]*\bmarkdown\s*=", re.I)
_TITLE_ID = re.compile(r'<title\b[^>]*\bid\s*=\s*"([^"]+)"', re.I)
# <figure> ... <svg>…</svg> ... </figure>（figcaption を挟んでもよい）
_SVG_WRAPPED = re.compile(r"<figure\b[^>]*>\s*<svg\b.*?</svg>.*?</figure>", re.I | re.S)


def check_svg(docs):
    """インライン SVG の記法規約。違反メッセージのリストを返す（FAIL）。"""
    fails = []
    for rel, lines in docs:
        text = "\n".join(lines)
        if "<svg" not in text:
            continue
        # lint-ok: SVG5 を書いた行は当該ファイルの検査5を免除（理由をコメントで残す運用）
        if re.search(r"lint-ok:\s*SVG5", text):
            continue
        if _FIGURE_MD.search(text):
            fails.append(f"{rel}: <figure> に markdown 属性がある"
                         f"（SVG内テキストがMarkdown処理され壊れる）")
        # <svg> の直前が <figure> で、</svg> の直後が </figure> であること。
        # 生の <svg> は python-markdown に <p> で分割され、図の中身が失われる。
        if len(_SVG_WRAPPED.findall(text)) != len(_SVG_BLOCK.findall(text)):
            fails.append(f"{rel}: <svg> が <figure> で包まれていない"
                         f"（python-markdown が <p> で分割し、ビルド後HTMLで図の中身が消える）")
        ids = []
        for block in _SVG_BLOCK.findall(text):
            open_tag = _SVG_OPEN.search(block)
            open_tag = open_tag.group(0) if open_tag else "<svg>"
            if not re.search(r'\bwidth\s*=', open_tag) or not re.search(r'\bheight\s*=', open_tag):
                fails.append(f"{rel}: <svg> に width/height が無い"
                             f"（figure{{width:fit-content}} で約26pxに潰れる）")
            if 'role="img"' not in open_tag.replace("'", '"'):
                fails.append(f"{rel}: <svg> に role=\"img\" が無い")
            if "<title" not in block:
                fails.append(f"{rel}: <svg> に <title> が無い（支援技術で内容が読めない）")
            for var in SVG_BANNED_VARS:
                if var in block:
                    fails.append(f"{rel}: SVG が {var} を使っている"
                                 f"（配色切替/ダークでコントラスト 3:1 未満になる組合せがある）")
            for hexval in _HEXCOLOR.findall(block):
                fails.append(f"{rel}: SVG で色をハードコードしている（{hexval}）"
                             f"。--md-default-fg-color 系または --ei-fig-* トークンを使う")
            ids += _TITLE_ID.findall(block)
        dupes = {i for i in ids if ids.count(i) > 1}
        for dup in sorted(dupes):
            fails.append(f"{rel}: <title id=\"{dup}\"> がページ内で重複している")
    return fails


# ---------------------------------------------------------------------------
# 検査6: 想定外スクリプトの混入（生成テキストの取り違え検知）
# ---------------------------------------------------------------------------
# 本 Wiki は日本語＋ラテン文字＋記号で書かれる。キリル・ハングル・タイ等が
# 本文に現れたら、ほぼ確実に生成・コピペ時の混入事故。
# 実事案 2026-07-28: 30秒まとめの一括追加でロシア語断片が1ページに混入した
# （目視では気づきにくく、ビルドも lint も通ってしまった）。
_UNEXPECTED_SCRIPT = re.compile(
    r"[Ѐ-ӿ"      # キリル
    r"가-힯"       # ハングル音節
    r"฀-๿"       # タイ
    r"؀-ۿ"       # アラビア
    r"֐-׿"       # ヘブライ
    r"ऀ-ॿ]"      # デーヴァナーガリー
)


def check_unexpected_script(docs):
    """検査6: 想定外スクリプトの混入。違反メッセージのリストを返す（FAIL）。"""
    fails = []
    for rel, lines in docs:
        for i, line in enumerate(lines):
            if "lint-ok: SCRIPT6" in line:
                continue
            m = _UNEXPECTED_SCRIPT.search(line)
            if m:
                fails.append(f"{rel}:{i+1}: 想定外スクリプトの混入（{m.group(0)!r}）"
                             f"— 生成/コピペ事故の可能性。意図的なら lint-ok: SCRIPT6")
    return fails


